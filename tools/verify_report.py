def _extract_text_from_pdf(path: str) -> str:
    """Read binary stream and extract text strings from PDF."""
    try:
        with open(path, "rb") as f:
            data = f.read()
        return data.decode("latin-1", errors="replace")
    except Exception:
        return ""


def _extract_text_from_html(path: str) -> str:
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            return f.read()
    except Exception:
        return ""


def extract_embedded_hash(report_path: str) -> Optional[str]:
    """
    Extract the SHA-256 authenticity hash embedded inside any SMP report
    format (.json, .md, .pdf, .html).
    """
    if not os.path.exists(report_path):
        return None

    ext = os.path.splitext(report_path)[1].lower()

    # Case A: JSON Report
    if ext == ".json":
        try:
            with open(report_path, "r", encoding="utf-8") as f:
                data = json.load(f)
            return data.get("authenticity_hash")
        except Exception:
            return None

    # Case B: Markdown Report
    if ext in (".md", ".markdown"):
        try:
            with open(report_path, "r", encoding="utf-8", errors="replace") as f:
                text = f.read()
            return extract_markdown_digest(text)
        except Exception:
            return None

    # Case C: PDF Report
    if ext == ".pdf":
        text = _extract_text_from_pdf(report_path)
        m = re.search(r"([a-f0-9]{64})", text)
        if m:
            return m.group(1)
        pattern = re.compile(re.escape(HASH_MARKER_START) + r"([a-f0-9]{64})" + re.escape(HASH_MARKER_END))
        m = pattern.search(text)
        if m:
            return m.group(1)

    # Case D: HTML Report
    if ext in (".html", ".htm"):
        text = _extract_text_from_html(report_path)
        m = re.search(r"([a-f0-9]{64})", text)
        if m:
            return m.group(1)
        pattern = re.compile(re.escape(HASH_MARKER_START) + r"([a-f0-9]{64})" + re.escape(HASH_MARKER_END))
        m = pattern.search(text)
        if m:
            return m.group(1)

    return None


def extract_metadata_from_report(report_path: str) -> Dict[str, Any]:
    """Extract metadata details from report."""
    ext = os.path.splitext(report_path)[1].lower()
    meta = {}

    if ext == ".json":
        try:
            with open(report_path, "r", encoding="utf-8") as f:
                data = json.load(f)
            stats = data.get("statistics", {})
            return {
                "format": "JSON",
                "report_id": data.get("report_id"),
                "engagement_id": data.get("engagement_id"),
                "target": data.get("target"),
                "operator": data.get("operator"),
                "smp_version": data.get("smp_version") or data.get("report_generator_version"),
                "generated_at": data.get("generated_at"),
                "risk_rating": stats.get("risk_rating"),
                "total_findings": stats.get("total_findings"),
                "critical": stats.get("critical"),
                "high": stats.get("high"),
                "medium": stats.get("medium"),
                "low": stats.get("low"),
                "authenticity_hash": data.get("authenticity_hash"),
            }
        except Exception:
            return {}

    if ext in (".md", ".markdown"):
        try:
            with open(report_path, "r", encoding="utf-8", errors="replace") as f:
                text = f.read()

            def _find_field(name):
                m = re.search(rf"\*\*{name}\*\*.*?`([^`]+)`", text)
                return m.group(1).strip() if m else None

            meta["format"] = "Markdown"
            meta["report_id"] = _find_field("Report ID")
            meta["engagement_id"] = _find_field("Engagement ID")
            meta["target"] = _find_field("Target")
            meta["operator"] = _find_field("Operator")
            meta["generated_at"] = _find_field("Generated")
            meta["authenticity_hash"] = extract_markdown_digest(text)
            return meta
        except Exception:
            return {}

    if ext == ".pdf":
        text = _extract_text_from_pdf(report_path)
        meta_match = re.search(r"SMP-META-START(.*?)SMP-META-END", text, re.DOTALL)
        if meta_match:
            try:
                return json.loads(meta_match.group(1).strip())
            except Exception:
                pass
        return {"format": "PDF", "authenticity_hash": extract_embedded_hash(report_path)}

    return meta


